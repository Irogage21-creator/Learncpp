//Lecture 16 : Introduction to String Methods : 

# include <iostream>

int main(){

    using std::cout;
    using std::cin;
    using std::string;

    string name;

    cout << "What is your name : ";
    std::getline(cin , name);cout << '\n';

//------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
    
//length method : In this method , we specify the condition on the length of the string :

    if(name.length() > 16){ //This puts a condition on the length of string that it should be not greater than 16
                            //format variable.length() >=< condition 

        cout << "Your name cannot have more than 16 characters ! \n";
    }
    else{
        cout << "Hello "<< name << '\n';
    }
//------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

//Empty method : This method checks whether a string contains any text or is completely empty :

    cout << "What is your name : ";
    std::getline(cin , name);cout << '\n';

    if(name.empty()){ //format variable.empty()

        cout << "You have not entered your name . \n";
    }
    else{
        cout << "Hello "<< name << '\n';
    }
//------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

//Clear method : This method simply clear you input :

    cout << "What is your name : ";
    std::getline(cin , name);cout << '\n';

    name.clear();//this is how you write variable.clear()

    cout << "Hello "<< name << '\n';

//------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

//Append method : In this method we can add an additional string at the end of a string input : 

    
    cout << "What kind of username you want for gmail , please enter : ";
    std::getline(cin , name);cout << '\n';

    name.append("@gmail.com");//  variable.append("string")

    cout << "Your gmailID is : "<< name << '\n';

//------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

//At method : This method is used to find out which letter is present on a particular index :

    cout << "What is your name : ";
    std::getline(cin , name);cout << '\n';

    cout << name.at(0) << '\n';//  variable.at(index which starts from 0 to last index of domain)
    cout << name.at(4) << '\n';
    cout << name.at(9) << '\n';
    //cout << name.at(45) << '\n';This is out of domain
    //cout << name.at(32) << '\n';This is out of domain
    cout << name.at(1) << '\n';
//------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

//Insert method : This method is used to insert a string in a particular index :

    cout << "What is your name : ";
    std::getline(cin , name);cout << '\n';

    name.insert(0 , "@");// variable.insert(index , string)
    cout << name << '\n';
//------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

//Find method : This method finds the exact char which you enter :

    cout << "What is your name : ";
    std::getline(cin , name);cout << '\n';

    cout << name.find('d') << '\n';// cout << variable.find(char);
    cout << name.find(' ') << '\n';
    //cout << name.find(3); This will give error 
    //cout << name.fin("Indrajeet");this will give index of I 

//------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

//Erase method : This method erase characters in a interval of Index :

    cout << "What is your name : ";
    std::getline(cin , name);cout << '\n';

    name.erase(0 , 5);// variable.erase(index1 , index2)

    cout << name << '\n';
//----------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

    //Lecture 16 ends


    return 0;
}